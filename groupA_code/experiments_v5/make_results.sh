#!/bin/bash
# writes RESULTS.md: every v5 table from the CSV files in results/ (run from arena/v5)
cd "$(dirname "$0")"
R=results
{
echo "# Sushi Go agent v5 – experiment results"
echo
echo "Generated by \`make_results.sh\` from the CSV files in \`results/\`. Opponents: v2 (\`refv2\`) and TAG's ISMCTS"
echo "(\`players.mcts\`, benchmark only), both with the same CPU budget as our agent. Paired differences: same seed ="
echo "same deals and seats; ± is 1.96 standard errors of the per-game differences."
echo
echo "### 3 players, 100 ms, seed 7 (paired with the v4 agent on this machine)"
echo
python3 table.py $R/v5_base3p100.csv \
  "v4 (final agent, base)=$R/v5_base3p100.csv" \
  "+ X3 (3-player card model)=$R/v5_X3_3p100.csv" \
  "+ N, λ 0.5 (denial)=$R/v5_N05_3p100.csv" \
  "+ V2D (terminal value scale 2, σ decay 0.5)=$R/v5_V2D_3p100.csv" \
  "+ W1 (leader weight w 1.0)=$R/v5_W1_3p100.csv" \
  "+ R3V2 (rollouts to the game end, terminal value scale 2)=$R/v5_R3V2_3p100.csv" \
  "K 0.35=$R/v5_K035_3p100.csv" | grep -v "| v5_base3p100 |" | grep -v "| missing |"
echo
echo "### 4 players, 100 ms, seed 7 (paired with the v4 validation run V_4p100 of the old machine, same deals)"
echo
python3 table.py ../results/V_4p100.csv "v4 (V_4p100, old machine)=../results/V_4p100.csv" \
  "+ X3 in the 4-player block=$R/v5_4X3_4p100.csv" | grep -v "| V_4p100 |" | grep -v "| missing |"
echo
echo "### Machine check: v4 on the old (18-core) and the new (4-core) machine, 3 players, 100 ms, seed 7"
echo
python3 table.py ../results/V_3p100.csv "v4, old machine (V_3p100)=../results/V_3p100.csv" \
  "v4, this machine (v5_base3p100)=$R/v5_base3p100.csv" | grep -v "| V_3p100 |"
if [ -f $R/v5_comp_3p1000.csv ] || [ -f $R/v5_comp_4p500.csv ]; then
echo
echo "### The competition files on this machine (wall-clock guard on, 3 game threads)"
echo
echo "Paired with the first games of the v4 validation runs (same deals; those used the benchmark files without the guard)."
echo
[ -f $R/v5_comp_3p1000.csv ] && python3 table.py ../results/V_3p900.csv "v4 validation, 900 ms (V_3p900)=../results/V_3p900.csv" \
  "SushiMCTS_1000ms.json, 3 players=$R/v5_comp_3p1000.csv" | grep -v "| V_3p900 |"
echo
[ -f $R/v5_comp_4p500.csv ] && python3 table.py ../results/V_4p500.csv "v4 validation, 500 ms (V_4p500)=../results/V_4p500.csv" \
  "SushiMCTS_500ms.json, 4 players=$R/v5_comp_4p500.csv" | grep -v "| V_4p500 |"
fi
} > RESULTS.md
echo "RESULTS.md written"
