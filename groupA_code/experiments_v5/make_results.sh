#!/bin/bash
# writes RESULTS.md: every v5 table from the CSV files in results/ (run from arena/v5)
cd "$(dirname "$0")"
R=results
{
echo "# Sushi Go agent v5 – experiment results"
echo
echo "Generated by \`make_results.sh\` from the CSV files in \`results/\`. Opponents: v2 (\`refv2\`) and TAG's ISMCTS"
echo "(\`players.mcts\`, benchmark only), both with the same CPU budget as our agent. Paired differences: same seed ="
echo "same deals and seats; ± is 1.96 standard errors of the per-game differences."
echo
echo "### 3 players, 100 ms, seed 7 (paired with the v4 agent on this machine)"
echo
python3 table.py $R/v5_base3p100.csv \
  "v4 (final agent, base)=$R/v5_base3p100.csv" \
  "+ X3 (3-player card model)=$R/v5_X3_3p100.csv" \
  "+ N, λ 0.5 (denial)=$R/v5_N05_3p100.csv" \
  "+ V2D (terminal value scale 2, σ decay 0.5)=$R/v5_V2D_3p100.csv" \
  "+ W1 (leader weight w 1.0)=$R/v5_W1_3p100.csv" \
  "+ R3V2 (rollouts to the game end, terminal value scale 2)=$R/v5_R3V2_3p100.csv" \
  "K 0.35=$R/v5_K035_3p100.csv" | grep -v "| v5_base3p100 |" | grep -v "| missing |"
echo
echo "### 4 players, 100 ms, seed 7 (paired with the v4 validation run V_4p100 of the old machine, same deals)"
echo
python3 table.py ../results/V_4p100.csv "v4 (V_4p100, old machine)=../results/V_4p100.csv" \
  "+ X3 in the 4-player block=$R/v5_4X3_4p100.csv" | grep -v "| V_4p100 |" | grep -v "| missing |"
echo
echo "### Machine check: v4 on the old (18-core) and the new (4-core) machine, 3 players, 100 ms, seed 7"
echo
python3 table.py ../results/V_3p100.csv "v4, old machine (V_3p100)=../results/V_3p100.csv" \
  "v4, this machine (v5_base3p100)=$R/v5_base3p100.csv" | grep -v "| V_3p100 |"
echo
echo "### Stronger field: v4 against two TAG ISMCTS (3 players, 100 ms, seed 7)"
echo
python3 tab.py "v4 vs 2 x ISMCTS=$R/v5_field_3p100.csv" "v4 vs 2 x ISMCTS, with r2_field_3p100b (500)=$R/v5_field_3p100_all.csv"
if [ -f $R/v5_comp_3p1000.csv ] || [ -f $R/v5_comp_4p500.csv ]; then
echo
echo "### The competition files on this machine (wall-clock guard on, 3 game threads)"
echo
echo "Paired with the first games of the v4 validation runs (same deals; those used the benchmark files without the guard)."
echo
[ -f $R/v5_comp_3p1000.csv ] && python3 table.py ../results/V_3p900.csv "v4 validation, 900 ms (V_3p900)=../results/V_3p900.csv" \
  "SushiMCTS_1000ms.json, 3 players=$R/v5_comp_3p1000.csv" "SushiMCTS_1000ms.json, 3 players, both batches=$R/v5_comp_3p1000_all.csv" | grep -v "| V_3p900 |"
echo
[ -f $R/v5_comp_4p500.csv ] && python3 table.py ../results/V_4p500.csv "v4 validation, 500 ms (V_4p500)=../results/V_4p500.csv" \
  "SushiMCTS_500ms.json, 4 players=$R/v5_comp_4p500.csv" | grep -v "| V_4p500 |"
fi
echo
echo "## Report revision (r2 runs, \`q2.txt\`)"
echo
echo "### Held-out validation: seed block 100 000 (game seeds 100 000 – 100 499), disjoint from all earlier deals"
echo
echo "Opponents: v2 and TAG's ISMCTS at the same budget (\`arena/agents/b<budget>/ref.json\`, \`tagmcts.json\`)."
echo
echo '```'
python3 tab.py "3p, 100 ms=$R/r2_val_3p100.csv" "3p, 500 ms=$R/r2_val_3p500.csv" \
  "3p, 900 ms=$R/r2_val_3p900.csv" \
  "4p, 100 ms=$R/r2_val_4p100.csv" "4p, 500 ms (F+L8)=$R/r2_val_4p500.csv"
echo '```'
echo
echo "The 500 ms, 900 ms and v3 500 ms runs were played in four chunks each (\`*_c0\` … \`*_c3\`, seeds 100 000 + offset,"
echo "offsets 0, 126, 252, 378 with 3 players and 0, 128, 256, 384 with 4) after a container restart had lost a running"
echo "experiment; \`merge_chunks.py\` joins them into one 500-game run with the deals, seats and opponent order of seed"
echo "block 100 000 (see its docstring), so they pair with the other held-out runs by game number."
echo
echo "### v3 (sequential tree, H + B + D + P + R + M) on the held-out deals, paired with the final agent"
echo
[ -f $R/r2_v3_3p100.csv ] && python3 table.py $R/r2_v3_3p100.csv "v3, 100 ms (base)=$R/r2_v3_3p100.csv" "final agent, 100 ms=$R/r2_val_3p100.csv" | grep -v "| r2_v3_3p100 |" | grep -v "| missing |"
echo
[ -f $R/r2_v3_3p500.csv ] && python3 table.py $R/r2_v3_3p500.csv "v3, 500 ms (base)=$R/r2_v3_3p500.csv" "final agent, 500 ms=$R/r2_val_3p500.csv" | grep -v "| r2_v3_3p500 |" | grep -v "| missing |"
echo
echo "### The final agent across budgets on the held-out deals (paired with 100 ms)"
echo
python3 table.py $R/r2_val_3p100.csv "100 ms (base)=$R/r2_val_3p100.csv" "500 ms=$R/r2_val_3p500.csv" "900 ms=$R/r2_val_3p900.csv" | grep -v "| r2_val_3p100 |" | grep -v "| missing |"
echo
echo
echo "Seats of every agent (from the logs):"
echo
echo '```'
for l in r2_val_3p100 r2_val_3p500 r2_val_3p900 r2_val_4p100 r2_val_4p500 r2_duct_3p100; do
  [ -f $R/$l.log ] && { echo "$l"; grep -E "win [0-9.]+% over" $R/$l.log; }
done
echo '```'
echo
echo "### Against TAG's decoupled information-set MCTS (SushiGoDUCT.json at 100 ms) and TAG's ISMCTS, 3 players, seed 100 000"
echo
echo '```'
python3 tab.py "v4 vs DUCT + ISMCTS=$R/r2_duct_3p100.csv"
echo '```'
echo
echo "### H replaced by TAG's LeaderHeuristic (K 7.5), 3 players, 100 ms, seed 7 (paired with \`v5_base3p100\`)"
echo
python3 table.py $R/v5_base3p100.csv "v4 (final agent, base)=$R/v5_base3p100.csv" \
  "H → LeaderHeuristic, K 7.5=$R/r2_lead_3p100.csv" | grep -v "| missing |" | grep -v "| v5_base3p100 |"
echo
echo "### Diagnostics"
echo
echo "Iterations per decision of v3 and v4 (\`arena.Probe\`, 2 games per budget):"
echo
echo '```'
cat $R/probe_iterations.txt 2>/dev/null
echo '```'
echo
echo "Four-player search of the final 500 ms agent on 73 positions from random games (\`run_treestats.sh\`: Bench4,"
echo "TreeStats4, Agree4 of \`experiments_v4/dev\`):"
echo
echo '```'
cat $R/bench4.txt $R/treestats4.txt $R/agree4.txt 2>/dev/null
echo '```'
} > RESULTS.md
echo "RESULTS.md written"
